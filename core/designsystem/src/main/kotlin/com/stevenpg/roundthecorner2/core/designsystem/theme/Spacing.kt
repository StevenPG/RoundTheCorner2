package com.stevenpg.roundthecorner2.core.designsystem.theme

import androidx.compose.ui.unit.dp

/**
 * 4dp-grid spacing tokens. Use these instead of raw `dp` literals so padding is
 * consistent across screens and easy to tune globally.
 */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val xxxl = 48.dp

    /** Standard horizontal inset for screen content. */
    val screenHorizontal = 20.dp
}
